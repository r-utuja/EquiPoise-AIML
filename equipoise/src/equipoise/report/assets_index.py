def build_index(reports: Path) -> tuple[str, list[str]]:
    """Markdown text and the list of EXTRA files that are missing."""
    per: dict[str, list[str]] = {k: [] for k, _ in SECTIONS}
    for sub in ("figures", "tables"):
        for f in sorted((reports / sub).glob("*")):
            if f.suffix not in (".png", ".md"):
                continue
            prefix = f.name.split("_")[0]
            sec = PREFIX_SECTION.get(prefix)
            if sec:
                per[sec].append(f"{sub}/{f.name}")
    missing = []
    for sec, files in EXTRA.items():
        for rel in files:
            if not (reports / rel).is_file():
                missing.append(rel)
            if rel not in per[sec]:
                per[sec].append(rel)
    lines = ["# Report assets", "",
             "Generated by `python -m equipoise report-assets`; do not edit by hand. Every "
             "figure and table under `reports/` is mapped to a section of the report template. "
             "Tables exist as `.csv` (data) and `.md` (paste-ready); only `.md` is listed.", "",
             "> Research prototype, not for clinical use. Data: DRCR Retina Network, "
             "Protocol T.", ""]
    for sec, title in SECTIONS:
        lines += [f"## {sec}. {title}", ""]
        if sec in NOTES:
            lines += [NOTES[sec], ""]
        for rel in per[sec]:
            flag = "" if (reports / rel).is_file() else "  **(missing: run the pipeline)**"
            lines.append(f"- [`{rel}`]({rel}){flag}")
        shots = [s for k, s in SCREENSHOTS if k == sec]
        if shots:
            lines += ["", "Screenshots to take manually:"]
            lines += [f"- [ ] {s}" for s in shots]
        lines.append("")
    return "\n".join(lines), missing
