"""Write pinned requirements*.txt from the packages actually installed in this environment.

For the core package and for each installed extra, walk the dependency tree through
`importlib.metadata` and pin every reachable distribution to its installed version:

  requirements.txt          core dependencies
  requirements-<extra>.txt  extra-only additions (written only if the extra is installed)

Usage:
    python scripts/freeze_requirements.py
"""

from __future__ import annotations

from importlib import metadata
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

PACKAGE = "equipoise"
ROOT = Path(__file__).resolve().parents[1]


PLATFORM_MARKERS = ("sys_platform", "platform_system", "os_name", "platform_machine")


def _closure(reqs: list[Requirement], extras: set[str]) -> dict[str, str] | None:
    """Installed name -> pinned spec for everything reachable; None if something is missing.

    Platform-conditional dependencies (e.g. pywin32 on Windows) keep their marker so the
    file still installs on Linux CI and Docker.
    """
    seen: dict[str, str] = {}
    stack = [(r, extras) for r in reqs]
    while stack:
        req, active = stack.pop()
        env_extras = active or {""}
        if req.marker and not any(req.marker.evaluate({"extra": e}) for e in env_extras):
            continue
        name = canonicalize_name(req.name)
        if name in seen:
            continue
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            return None
        marker = str(req.marker) if req.marker else ""
        platform_only = any(m in marker for m in PLATFORM_MARKERS) and "extra" not in marker
        keep = marker if platform_only else ""
        seen[name] = dist.version + (f" ; {keep}" if keep else "")
        for sub in dist.requires or []:
            stack.append((Requirement(sub), set(req.extras)))
    return seen


def main() -> None:
    dist = metadata.distribution(PACKAGE)
    all_reqs = [Requirement(r) for r in dist.requires or []]
    core_reqs = [r for r in all_reqs if not (r.marker and "extra" in str(r.marker))]
    core = _closure(core_reqs, set())
    assert core is not None, "core dependencies are not all installed"
    header = "# Generated by scripts/freeze_requirements.py from the installed environment.\n"
    (ROOT / "requirements.txt").write_text(
        header + "".join(f"{n}=={v}\n" for n, v in sorted(core.items())), encoding="utf-8")
    print(f"requirements.txt: {len(core)} packages")
    for extra in dist.metadata.get_all("Provides-Extra") or []:
        reqs = [r for r in all_reqs if r.marker and r.marker.evaluate({"extra": extra})]
        pins = _closure(reqs, {extra})
        out = ROOT / f"requirements-{extra}.txt"
        if pins is None:
            print(f"requirements-{extra}.txt: skipped (extra not installed)")
            continue
        extra_only = {n: v for n, v in pins.items() if n not in core}
        out.write_text(
            header + "-r requirements.txt\n"
            + "".join(f"{n}=={v}\n" for n, v in sorted(extra_only.items())),
            encoding="utf-8",
        )
        print(f"{out.name}: {len(extra_only)} extra packages")


if __name__ == "__main__":
    main()
